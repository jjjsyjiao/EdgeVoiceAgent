package com.edgevoice.agent.core.history

import java.time.ZoneId
import java.net.URI

/** 历史工具与实时相机开关独立：只有显式配置、鉴权端点齐备时才注册。 */
data class HistoryMemoryConfig(
    val enabled: Boolean = false,
    val baseUrl: String = "",
    val apiToken: String = "",
    val timeZoneId: String = ZoneId.systemDefault().id,
    /** Only the debug app may explain its local computer/USB connection to the user. */
    val debugConnectionHints: Boolean = false,
) {
    val active: Boolean get() = enabled && apiToken.isNotBlank() && runCatching {
        val endpoint = URI(baseUrl)
        (endpoint.scheme == "https" || endpoint.scheme == "http") && !endpoint.host.isNullOrBlank() &&
            endpoint.userInfo == null && endpoint.query == null && endpoint.fragment == null &&
            apiToken.none { it == '\r' || it == '\n' } && ZoneId.of(timeZoneId).id.isNotBlank()
    }.getOrDefault(false)

    // BuildConfig 来自本地配置，不允许调试输出把用户凭据带进日志。
    override fun toString(): String = "HistoryMemoryConfig(enabled=$enabled, configured=$active, timeZoneId=$timeZoneId)"
}

/** capturedAtMs 是拍摄时间，recordedAtMs 是服务器保存时间，二者不可互换。 */
data class HistoryMemoryRecord(
    val recordId: String,
    val sessionId: String,
    val capturedAtMs: Long,
    val objectName: String,
    val recordedAtMs: Long = capturedAtMs,
    val aliases: List<String> = emptyList(),
    val location: String = "",
    val note: String = "",
    val jpeg: ByteArray = byteArrayOf(),
    val source: String = "user_recorded",
    val score: Double = 1.0,
) {
    override fun toString(): String = "HistoryMemoryRecord(recordId=$recordId, capturedAtMs=$capturedAtMs, imageBytes=${jpeg.size})"
}

enum class HistorySearchStatus { MATCHED, NO_MATCH, EVIDENCE_UNAVAILABLE }

enum class HistorySearchIntent(val wireValue: String) {
    RECALL("recall"), FIND_LAST_LOCATION("find_last_location"), COMPARE("compare"),
}

/** Pixels and raw ASR are injected by the client from this turn, never generated by a tool call. */
data class HistorySearchRequest(
    val query: String,
    val rawQuery: String? = null,
    val queryImage: ByteArray? = null,
    val intent: HistorySearchIntent = HistorySearchIntent.RECALL,
    val fromTsMs: Long? = null,
    val toTsMs: Long? = null,
    val limit: Int = 3,
) {
    override fun toString(): String = "HistorySearchRequest(intent=$intent, imageBytes=${queryImage?.size ?: 0}, limit=$limit)"
}

enum class HistoryRetrievalStatus { READY, INDEXING, DEGRADED, UNAVAILABLE }

data class HistoryRetrievalInfo(
    val mode: String,
    val status: HistoryRetrievalStatus,
    val pendingRecordsCount: Int = 0,
    val failedRecordsCount: Int = 0,
    val warnings: List<String> = emptyList(),
    val traceId: String? = null,
) {
    val incomplete: Boolean get() = status != HistoryRetrievalStatus.READY ||
        pendingRecordsCount > 0 || failedRecordsCount > 0 || warnings.any { it != "uncalibrated_similarity" }
    val uncalibratedSimilarity: Boolean get() = "uncalibrated_similarity" in warnings
}

data class HistoryCoverage(
    val fromTsMs: Long? = null,
    val toTsMs: Long? = null,
    val retentionDays: Int = 7,
    val recordsCount: Int = 0,
    val continuous: Boolean = false,
)

data class HistorySearchResult(
    val status: HistorySearchStatus,
    val records: List<HistoryMemoryRecord> = emptyList(),
    val coverage: HistoryCoverage = HistoryCoverage(),
    val unavailableRecordsCount: Int = 0,
    val retrieval: HistoryRetrievalInfo? = null,
)

enum class HistoryStatus { IDLE, CONFIRM_SAVE, SAVING, SAVED, SEARCHING, COMPARING, RESULT, NO_MATCH, EVIDENCE_UNAVAILABLE, ERROR }

/** 证据卡不替换实时字幕。图片只保留当前一次操作的少量结果。 */
data class HistoryUiState(
    val status: HistoryStatus = HistoryStatus.IDLE,
    val message: String? = null,
    val records: List<HistoryMemoryRecord> = emptyList(),
    /** Frozen preview awaiting an explicit tap; this image has not been sent to history storage. */
    val pendingJpeg: ByteArray? = null,
)

enum class HistoryFailureKind { AUTHENTICATION, UNAVAILABLE, NETWORK, TIMEOUT, INVALID_RESPONSE, INVALID_REQUEST, HTTP }

class HistoryMemoryException(
    val kind: HistoryFailureKind,
    val statusCode: Int? = null,
) : Exception("Visual memory request failed: ${kind.name}")

interface HistoryMemoryClient {
    suspend fun save(record: HistoryMemoryRecord): HistoryMemoryRecord

    /** 时间范围为 [fromTsMs, toTsMs)，省略范围时检索当前用户保留期内的跨会话记录。 */
    suspend fun search(
        query: String,
        fromTsMs: Long? = null,
        toTsMs: Long? = null,
        limit: Int = 3,
    ): HistorySearchResult

    /** Compatibility for existing clients; HTTP implementations should retain the structured fields. */
    suspend fun search(request: HistorySearchRequest): HistorySearchResult =
        search(request.query, request.fromTsMs, request.toTsMs, request.limit)

    suspend fun delete(recordId: String): Boolean
}
